import { readFile, writeFile } from "node:fs/promises";
import { Path, parse } from "opentype.js/dist/opentype.mjs";

const WORDS = ["Ouasti", "Hamza"];
const ACCENT_WORD = 0;
const FONT_SIZE = 100;
const PADDING = 4;
// Extra slant on top of the font's own, as a skew applied to the outlines.
const SLANT = Math.tan((10 * Math.PI) / 180);

const fontFile = await readFile(new URL("signature/GreatVibes-Regular.ttf", import.meta.url));
const font = parse(fontFile.buffer.slice(fontFile.byteOffset, fontFile.byteOffset + fontFile.byteLength));

// Glyphs are placed and scaled by hand: font.getPaths() throws on a GSUB
// lookup type opentype.js doesn't support. Coordinates are pre-rounded because
// opentype.js's own rounding writes NaN for float noise like 12.00000000000001.
const chars = WORDS.join(" ").split("");
const glyphs = chars.map((char) => font.charToGlyph(char));
const scale = FONT_SIZE / font.unitsPerEm;

function placeGlyph(glyph, offsetX) {
  const round = (value) => Math.round(value * 10) / 10;
  const x = (vx, vy) => round(offsetX + (vx + vy * SLANT) * scale);
  const y = (vy) => round(-vy * scale);
  const path = new Path();
  for (const cmd of glyph.path.commands) {
    if (cmd.type === "M") path.moveTo(x(cmd.x, cmd.y), y(cmd.y));
    else if (cmd.type === "L") path.lineTo(x(cmd.x, cmd.y), y(cmd.y));
    else if (cmd.type === "Q") path.quadraticCurveTo(x(cmd.x1, cmd.y1), y(cmd.y1), x(cmd.x, cmd.y), y(cmd.y));
    else if (cmd.type === "C")
      path.curveTo(x(cmd.x1, cmd.y1), y(cmd.y1), x(cmd.x2, cmd.y2), y(cmd.y2), x(cmd.x, cmd.y), y(cmd.y));
    else path.close();
  }
  return path;
}

let cursor = 0;
const paths = glyphs.map((glyph, index) => {
  const path = placeGlyph(glyph, cursor);
  const next = glyphs[index + 1];
  cursor += (glyph.advanceWidth + (next ? font.getKerningValue(glyph, next) : 0)) * scale;
  return path;
});

let x1 = Infinity;
let y1 = Infinity;
let x2 = -Infinity;
let y2 = -Infinity;
const letters = [];
let word = 0;
paths.forEach((path, index) => {
  if (chars[index] === " ") {
    word += 1;
    return;
  }
  const box = path.getBoundingBox();
  x1 = Math.min(x1, box.x1);
  y1 = Math.min(y1, box.y1);
  x2 = Math.max(x2, box.x2);
  y2 = Math.max(y2, box.y2);
  const d = path.toPathData({ decimalPlaces: 1, optimize: false, flipY: false });
  if (d.includes("NaN")) throw new Error(`Invalid path data for "${chars[index]}"`);
  letters.push({ char: chars[index], word, accent: word === ACCENT_WORD, d });
});

const round = (value) => Math.round(value * 10) / 10;
const viewBox = [x1 - PADDING, y1 - PADDING, x2 - x1 + PADDING * 2, y2 - y1 + PADDING * 2].map(round).join(" ");

const source = `// Generated by scripts/build-signature.mjs from Great Vibes (SIL OFL 1.1). Do not edit.
export const signature = ${JSON.stringify({ viewBox, letters }, null, 2)} as const;
`;
await writeFile(new URL("../app/signature.generated.ts", import.meta.url), source);
console.log(`Signature: ${letters.length} letters, viewBox ${viewBox}`);
